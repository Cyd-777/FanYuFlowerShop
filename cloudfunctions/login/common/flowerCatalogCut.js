function buildVarietyDescription(row) {
  const parts = []
  if (row.color && row.color !== '多色') parts.push(row.color)
  else if (row.color === '多色') parts.push('多色可选')
  if (row.features?.length) parts.push(row.features.slice(0, 4).join('、'))
  return parts.join('；') + '。'
}

function buildFlowerSeedFromCatalog() {
  const byKind = new Map()
  for (const row of CUT_FLOWER_CATALOG) {
    if (!byKind.has(row.kind)) byKind.set(row.kind, [])
    byKind.get(row.kind).push(row)
  }

  const seed = []
  for (const [kindName, kindRows] of byKind) {
    const meta = KIND_META[kindName]
    if (!meta) continue
    seed.push({
      name: kindName,
      icon: meta.icon,
      sort: meta.sort,
      defaultUnit: meta.defaultUnit,
      description: meta.description,
      varieties: kindRows.map((row, idx) => ({
        name: row.variety,
        aliases: row.aliases || [],
        color: row.color || '',
        featureTags: row.features || [],
        description: buildVarietyDescription(row),
        sort: 100 - idx,
      })),
    })
  }
  return seed.sort((a, b) => b.sort - a.sort)
}

